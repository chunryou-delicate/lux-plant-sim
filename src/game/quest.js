export function questOf(id) { return QUESTS.find(q => q.id === id) || RETIRED_QUESTS.find(q => q.id === id) || null; }

/* 「지금 할 일」 한 줄. ⚠ `todo` 가 함수인 것은 **수를 정의에서 읽게** 하려는 것이다 */
export function questTodo(q, s) {
  const d = questOf(typeof q === 'string' ? q : (q && q.id)) || q;
  if (!d || typeof d.todo !== 'function') return null;
  /* ★ 2026-08-17 — 둘째 인자는 **지금 상태**다(없어도 된다). 「이미 한 일을 하라고
     시키는 줄」을 없애려면 그 줄이 지금을 볼 수 있어야 한다 — 끝나는 조건은 안 건드린다. */
  try { return d.todo(d, s); } catch { return null; }
}

/* ── 판정 ───────────────────────────────────────────────────────────── */

/* 끝낸 것 — **`stamina.questsTaken` 이 정본이다.** 여기서 따로 안 센다.
   ⚠ 「받았다」와 「끝냈다」가 같은 칸인 것이 맞다: 보상을 받는 순간이 곧 끝낸 순간이고,
     둘을 갈라 두면 반드시 한쪽이 낡는다(이 저장소가 열여섯 번 밟은 그 모양). */
export function doneIdsOf(S) {
  const t = S && S.stamina && Array.isArray(S.stamina.questsTaken) ? S.stamina.questsTaken : [];
  return t.filter(id => QUEST_IDS.includes(id));
}

/* 지금 이 판의 퀘스트 상태. **기억하지 않는다 — 스냅샷에서 매번 센다.**

   ══ ★★★ 화면 계약 (2026-08-16 · 박사님 *"한 번에 보여주고… 단계적 목표로"*) ═══
   ⚠ **예전 칸은 하나도 안 없앴다.** `game.html` 이 `v.next.todo`·`v.all`·`v.done` 을
     읽고 있고 `test_quest`·`test_questui` 가 그것을 못 박는다. 아래는 **더 낸 것**이다.

     done        끝낸 id 들            (예전 그대로)
     open        지금 열린 id 들        (예전 그대로)
     next        지금 할 **하나**       (예전 그대로 · null 가능)
     all         모든 줄               (예전 그대로 + 아래 세 칸이 늘었다)
   ── 새로 내는 것 ───────────────────────────────────────────────────────
     current     `next` 와 **같은 객체**. 이름이 뜻을 말하라고 둔 것뿐이다
     upcoming    ★ **다음에 올 줄들**(아직 안 끝난 것 중 `current` 뒤 전부 · 정의 순서).
                 화면이 `slice(0, QUEST_PREVIEW)` 해서 **잠긴 채로** 그린다.
                 ⚠ 코어가 안 자른다 — 몇 줄이 들어가나는 폭의 일이다
     counts      { total, done, open, locked }
     stage       'first_play' | 'main' | 'clear' — **지금 어느 마디인가**
                 초반 사슬에 안 끝난 줄이 하나라도 있으면 'first_play'
     chain       { index, total } — 초반 사슬의 **몇째/여덟**. 사슬이 끝났으면 null
   ── `all[]` 한 줄이 갖는 것 ────────────────────────────────────────────
     id · ko · todo · why · teaches · reward · state('done'|'open'|'locked')  (예전 그대로)
     stage       'first_play' | 'main'
     index       정의 순서(0부터)
     speaks      이 줄이 대사를 갖나 (2026-08-16 밤부터 **열여섯 줄 전부 true**)
   ══════════════════════════════════════════════════════════════════════ */
export function questView(S, snapshot) {
  const s = snapOf(snapshot);
  const doneIds = doneIdsOf(S);
  const ctx = { doneIds, S };
  const open = [], all = [];
  QUESTS.forEach((q, i) => {
    const isDone = doneIds.includes(q.id);
    let isOpen = false;
    if (!isDone) { try { isOpen = !!q.opens(s, { ...ctx, q }); } catch { isOpen = false; } }
    if (isOpen) open.push(q.id);
    all.push({ id: q.id, ko: q.ko, todo: questTodo(q, s), why: q.why, teaches: q.teaches,
               /* ★ 2026-08-23 — **목표 수를 그대로 실어 준다.** 보기에는 `todo` 문장만 있어서
                  밖에서 「몇 개까지 늘리라는 것인가」를 알려면 **문장을 파싱**해야 했다.
                  숫자를 글에서 캐내는 것은 문구가 바뀌는 날 조용히 깨진다(§2.8 의 뒷면이다).
                  ⚠ 없는 줄은 `null` 이다 — 0 으로 메꾸지 않는다. */
               need: q.need || null,
               /* ★ 체력이 아닌 보상의 이름. 없으면 화면이 stamina 에서 「체력 +N」을 짓는다 */
               reward: q.reward || null,
               stage: stageOfQuest(q), index: i, speaks: q.speaks !== false,
               state: isDone ? 'done' : isOpen ? 'open' : 'locked' });
  });
  /* ★ 「지금 할 일」은 **하나만** 보여 준다. 목록을 내면 심부름 목록이 된다.
     고르는 자는 정의 순서다 — 그 순서가 곧 배우는 순서라서. */
  const nextId = open[0] || null;
  const next = nextId ? all.find(a => a.id === nextId) : null;
  /* ★ 「다음에 올 것」 — 지금 하나 **뒤**의 안 끝난 줄 전부다.
     ⚠ 끝낸 줄은 안 낸다(그건 `all` 의 'done' 이 갖는다). 잠긴 줄만이 아니라 **열린 줄도**
       들어간다 — 한 판에 둘이 같이 열리는 자리가 있고(예: `first_cut`+`buy_lamp`),
       그때 뒤엣것을 안 보여 주면 「다음에 올 것」이 거짓이 된다. */
  const from = next ? next.index + 1 : 0;
  const upcoming = all.filter(a => a.index >= from && a.state !== 'done');
  const doneN = doneIds.length;
  const counts = { total: all.length, done: doneN, open: open.length,
                   locked: all.length - doneN - open.length };
  /* ★ 마디 — 초반 사슬에 안 끝난 줄이 하나라도 남아 있으면 아직 첫 마디다 */
  const chainLeft = FIRST_PLAY_CHAIN_IDS.filter(id => !doneIds.includes(id));
  const stage = chainLeft.length ? STAGE_FIRST_PLAY
              : (doneN >= all.length ? STAGE_CLEAR : STAGE_MAIN);
  const chain = chainLeft.length
    ? { index: FIRST_PLAY_CHAIN_IDS.length - chainLeft.length + 1,
        total: FIRST_PLAY_CHAIN_IDS.length }
    : null;
  return { schema: QUEST_SCHEMA, done: doneIds, open, next, all,
           current: next, upcoming, counts, stage, chain };
}

/* 하루(또는 한 동작) 뒤에 판을 다시 본다. **사건을 낸다 — 보상은 안 준다.**
   ★ 보상은 부르는 쪽이 `stamina.grantStaminaQuest(S, id)` 로 준다.
     여기서 주면 이 파일이 stamina 를 알게 되고, 그러면 헤드리스에서 판정만 재는 길이 막힌다.

   반환 `{ opened: [id…], finished: [id…], events: [ev…] }`
     ev = { id: 'quest_opened'|'quest_done', questId, ko, todo }
   ⚠ **두 번 불러도 안전하다.** `finished` 는 아직 `questsTaken` 에 없는 것만 낸다. */
export function stepQuests(S, snapshot) {
  const s = snapOf(snapshot);
  const doneIds = doneIdsOf(S);
  const ctx = { doneIds, S };
  /* 「이미 열렸다고 말한 것」 — `_` 라 세이브에 안 실린다(§상태를 안 늘린다) */
  if (!Array.isArray(S._questOpen)) S._questOpen = [];
  const opened = [], finished = [], events = [];
  /* ★★★ 2026-08-17 — **이미 해 놓은 줄은 그 자리에서 끝난다** (박사님: *"퀘스트 나오기 전
       이미 달성했으면 자동 완료되게 해줘 (예를 들면 시루 8개 늘리기)"*)
     ══════════════════════════════════════════════════════════════════
     ⚠ 여는 것과 끝내는 것은 원래도 **한 걸음 안에서** 다 봤다. 문제는 **사슬**이었다:
       ⓑ 는 ⓐ 가 끝나야 열리는데, `doneIds` 를 맨 위에서 **한 번만** 읽으므로 ⓐ 가
       이번 걸음에 끝나도 ⓑ 는 **다음 걸음**에야 열린다. 걸음은 하루에 한 번이다.
       ⇒ 시루를 여덟 개까지 늘려 놓고 뒤늦게 사슬에 닿으면 **하루에 한 줄씩** 풀렸다.
     ⇒ **더 안 바뀔 때까지 돈다.** 이번 걸음에 끝난 것을 「끝난 것」으로 치고 다시 본다.
     ⚠ 천장을 둔다 — 규칙이 서로를 여는 고리를 만들면 여기서 영영 돈다. 줄 수만큼이면
       충분하고(한 바퀴에 적어도 하나는 끝나야 다음 바퀴가 있다), 넘으면 그건 고장이다.
     ⚠ 사람이 보는 순서는 안 바뀐다 — 「열렸다」가 먼저 실리고 「끝났다」가 뒤에 실린다. */
  const doneNow = new Set(doneIds);
  for (let round = 0; round <= QUESTS.length; round++) {
    let changed = false;
    const ctx2 = { doneIds: [...doneNow], S };
    for (const q of QUESTS) {
      if (doneNow.has(q.id)) continue;
      let isOpen = false;
      try { isOpen = !!q.opens(s, { ...ctx2, q }); } catch { isOpen = false; }
      if (!isOpen) continue;
      if (!S._questOpen.includes(q.id)) {
        S._questOpen.push(q.id);
        /* ★ 2026-09-02 — «열린 날»을 적는다(stamina.questsOpenedOn · 세이브에 실린다). 한 번 적으면 안 바꾼다 —
           다시 켜서 _questOpen 이 비어도 «처음 열린 날»이 남아야 독촉이 「며칠째」를 안 잊는다. */
        try {
          if (S.stamina && Number.isFinite(s.day)) {
            if (!S.stamina.questsOpenedOn || typeof S.stamina.questsOpenedOn !== 'object') S.stamina.questsOpenedOn = {};
            if (S.stamina.questsOpenedOn[q.id] == null) S.stamina.questsOpenedOn[q.id] = s.day;
          }
        } catch { }
        opened.push(q.id);
        events.push({ id: 'quest_opened', questId: q.id, ko: q.ko, todo: questTodo(q, s) });
        changed = true;
      }
      let isDone = false;
      try { isDone = !!q.done(s, { ...ctx2, q }); } catch { isDone = false; }
      if (isDone) {
        doneNow.add(q.id);
        finished.push(q.id);
        events.push({ id: 'quest_done', questId: q.id, ko: q.ko, todo: questTodo(q, s) });
        changed = true;
      }
    }
    if (!changed) break;
  }
  return { opened, finished, events };
}
