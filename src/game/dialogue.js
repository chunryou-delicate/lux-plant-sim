/* 이벤트 하나 → 대사 id. 계절·월세처럼 **같은 id 안에서 갈리는** 것만 여기서 본다. */
function scriptOf(ev) {
  const id = typeof ev === 'string' ? ev : (ev && ev.id);
  if (!id) return null;
  if (id === 'season') return ev.season === 'autumn' ? 'autumnCame'
                            : ev.season === 'winter' ? 'winterCame' : null;
  if (id === 'rent') return ev.first ? 'rentFirst' : 'rentAgain';
  /* ★ 퀘스트는 `questId` 로 갈린다 (2026-08-17 · 위 §QUEST_OPEN_SCRIPT) */
  if (id === 'quest_opened') return QUEST_OPEN_SCRIPT[ev && ev.questId] || null;
  if (id === 'quest_done')   return QUEST_DONE_SCRIPT[ev && ev.questId] || null;
  return EVENT_SCRIPT[id] || null;
}
/* 정렬용 열쇠 — season·rent 는 갈린 뒤의 이름으로 줄을 선다.
   ⚠ 퀘스트는 **갈리기 전 이름**으로 줄을 선다. 다섯 줄이 같은 날 겹칠 일이 규칙상 없고
     (여는 조건이 서로 다른 사건에 걸려 있다), 겹친다 해도 순서는 정의 순서 그대로가 맞다 —
     `scriptsForEvents` 가 `sort` 를 안정적으로 쓰므로 넘어온 차례가 유지된다. */
function orderKey(ev) {
  const id = typeof ev === 'string' ? ev : (ev && ev.id);
  if (id === 'season') return 'season_' + (ev.season || '');
  if (id === 'rent') return ev.first ? 'rent_first' : 'rent_again';
  return id;
}

/* 턴 결과 → 이번에 나올 대사. events 는 loop.js 의 `turn.events` 그대로다.
   ★Day 4 계약 순서(수확 → 식비 → 식물신 → 도착)는 EVENT_ORDER 가 지킨다. */
export function scriptsForEvents(events = []) {
  const list = (events || []).filter(Boolean);
  /* ══ ★★ 2026-08-16 — **한 줄이 같은 걸음에 열리고 끝나면 열림이 먼저다** ══════════
     `EVENT_ORDER` 는 `quest_done → quest_opened` 다. 그 순서는 **다른 두 줄**을 위한 것이고
     («①을 끝냈다 → 그래서 ②가 열린다» · 위 §EVENT_ORDER) 옳다. 그런데 **같은 줄**이
     한 걸음에 둘 다 나면 그 순서가 뒤집힌 말이 된다 — 「자리를 정했네」를 듣고 나서
     「가방에 둔 채로는 안 되는 거야?」를 듣는다.
   ⚠ 이건 지어낸 걱정이 아니다. **①`place_siru` 에서 실제로 난다** — `game.html` 이
     `checkQuests` 를 부르는 자리가 여섯인데(자르기·하루넘김·수확 둘·거래) **부팅도 놓기도
     그중에 없다.** 그래서 시루를 놓고 [다음 날]을 누르는 그 한 걸음에 ①이 열리고 끝난다.
   ⇒ 같은 `questId` 의 열림·완료가 한 묶음에 있으면 **열림을 완료와 같은 자리로 끌어온다.**
     `sort` 가 안정적이라 같은 자리끼리는 **넘어온 차례**가 남고, `stepQuests` 는 한 줄에 대해
     **열림을 먼저 push 한다**(quest.js §stepQuests). 그래서 열림 → 완료가 된다.
   ★ 다른 줄 사이의 「끝난 것이 먼저」는 **안 건드린다**(`test_quest ⑶` 이 그것을 못 박는다). */
  const openAndDone = new Set(
    list.filter(e => e && e.id === 'quest_opened' && e.questId)
        .map(e => e.questId)
        .filter(q => list.some(e => e && e.id === 'quest_done' && e.questId === q)));
  const rank = ev => {
    let key = orderKey(ev);
    if (key === 'quest_opened' && ev && openAndDone.has(ev.questId)) key = 'quest_done';
    const i = EVENT_ORDER.indexOf(key); return i < 0 ? 999 : i;
  };
  const out = [];
  for (const ev of [...list].sort((a, b) => rank(a) - rank(b))) {
    const s = scriptOf(ev);
    if (s && !out.includes(s)) out.push(s);
  }
  /* ★★ 식물신은 **주는 순간 바로 앞**에 붙는다 (2026-08-04 고침).
     예전에는 `harvest`(첫 수확) 뒤였다 — 그때가 곧 도착이었기 때문이다. 이제 도착이
     3회전째로 밀려서(first_play.monsteraArrivalDue) 옛 자리에 두면 신이 "줄 테니" 하고
     **며칠 뒤에** 물건이 온다. 주는 말과 오는 물건은 붙어 있어야 한다.
     ⚠ 도착보다 **앞**이라야 한다 — first_play.md §2 가 금지한 것이 "식물신이 도착 뒤에 말하는" 회차다. */
  const arr = out.indexOf('monsteraArrived');
  if (arr >= 0 && !out.includes('god1')) out.splice(arr, 0, 'god1');
  return out;
}

